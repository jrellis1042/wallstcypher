// build-config.js — generates config.js from the Nocturnal CRM credential files.
// Run: node scripts/build-config.js
// NEVER prints or logs the key values. Only the anon key is embedded;
// the service key is never read and never belongs in this repo.
const fs = require('fs');
const path = require('path');

const URL_FILE = path.join(process.env.HOME, 'workspace/nocturnal-crm/supabase-url.txt');
const KEY_FILE = path.join(process.env.HOME, 'workspace/nocturnal-crm/supabase-anon-key.txt');
const OUT = path.join(__dirname, '..', 'config.js');

const url = fs.readFileSync(URL_FILE, 'utf8').trim();
const key = fs.readFileSync(KEY_FILE, 'utf8').trim();
if (!url.startsWith('https://') || key.length < 20) {
  console.error('build-config: credential files look wrong (lengths only: url=' + url.length + ', key=' + key.length + ')');
  process.exit(1);
}
fs.writeFileSync(OUT,
  '// Generated by scripts/build-config.js — do not hand-edit.\n' +
  '// Holds the Supabase URL + ANON key only. Never put the service key here.\n' +
  'window.WSC_CONFIG = {\n' +
  '  SUPABASE_URL: ' + JSON.stringify(url) + ',\n' +
  '  SUPABASE_ANON_KEY: ' + JSON.stringify(key) + '\n' +
  '};\n');
console.log('build-config: wrote config.js (url length ' + url.length + ', key length ' + key.length + ')');
